package ru.projectx.datareference.service.onec;

import java.util.Objects;

/**
 * Чем закончился разбор одного сообщения: запись обновлена либо сообщение не наше.
 *
 * <p>«Не наше» — штатный и <b>частый</b> исход, а не ошибка: один поток 1С несёт данные
 * всех контрагентов 1С:УСК, а нам нужны только санатории с видом деятельности РВЛ.
 * Поэтому у пропуска обязательна причина: без неё «справочник пуст, потому что данных
 * нет» и «справочник пуст, потому что GUID вида деятельности задан неверно» выглядят
 * в базе одинаково.
 *
 * <p>Запечатанный тип, а не пара {@code boolean} + строка: причина существует ровно
 * у одного из исходов, и такая пара позволяла бы спросить причину у применённого
 * сообщения — то есть требовала бы проверки, о которой компилятор не напомнит.
 * Здесь она получается сама, из исчерпывающего {@code switch}.
 */
public sealed interface ImportResult {

    /** Запись создана или обновлена. */
    record Applied() implements ImportResult {
    }

    /**
     * Целевой справочник потока сообщением не пополнился — с объяснением, почему.
     *
     * <p>Не обязательно означает, что не записано ничего: страхователь из ТЗ-3 в свою
     * таблицу ложится, санаторием при этом не становясь. Отвечает исход на один вопрос —
     * появилось ли то, за чем в поток шли.
     */
    record Skipped(String reason) implements ImportResult {

        public Skipped {
            Objects.requireNonNull(reason, "reason");
        }
    }

    static ImportResult applied() {
        return new Applied();
    }

    static ImportResult skipped(String reason) {
        return new Skipped(reason);
    }
}
