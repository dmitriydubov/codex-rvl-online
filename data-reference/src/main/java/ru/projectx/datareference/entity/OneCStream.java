package ru.projectx.datareference.entity;

/**
 * Поток данных 1С:УСК — то, чем одно сырое сообщение отличается от другого.
 * По нему шедулер выбирает маппер, а дежурный понимает, что перед ним за строка.
 *
 * <p>Решения в сервисе принимаются по потоку, а не по имени очереди: имена очередей — конфигурация
 * контура и меняются (в документах контракта и на брокере они уже разные), а состав потоков задан
 * контрактом с 1С:УСК. Имя очереди в {@code inbound_message} тоже сохраняется, но как справочная
 * информация для разбора.
 */
public enum OneCStream {

    /** Полисы застрахованных вместе с программами и условиями обслуживания. Содержит ПДн. */
    POLICIES,

    /**
     * Договоры страхования. Сохраняются только ДМС, остальные продукты не наши. Страхователем бывает человек,
     * и тогда в теле сообщения его ФИО: это ПДн.
     */
    INSURANCE_CONTRACTS,

    /** Контрагенты-юрлица: ЛПУ ({@code thisIsLPU = true}) и страхователи ({@code false}). */
    CONTRAGENTS,

    /** Справочник МКБ-10. */
    MKB10,

    /** Договоры с ЛПУ. */
    LPU_CONTRACTS,

    /** Страховые программы и перечень доступных по ним учреждений. */
    PROGRAMS,

    /** Виды обращений за медицинской помощью. */
    APPEAL_TYPES,

    /** Контактная информация: адрес и регион ЛПУ. */
    LPU_CONTACTS,

    /**
     * Прейскуранты. Единственный поток, который приходит <b>двумя</b> очередями —
     * пакетами строк и одним финальным сообщением со счётчиками. Обе очереди дают
     * значение этого потока; какая именно, видно по имени очереди в строке сырья.
     */
    PRICE_LISTS,

    /** Услуги контрагентов по договорам. */
    CONTRAGENT_SERVICES
}
