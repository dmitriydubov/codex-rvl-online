package ru.projectx.datareference.entity;

/**
 * Поток данных 1С:УСК, по которому разбор выбирает маппер. Решения принимаются по потоку, а не по имени очереди:
 * имена очередей задаёт конфигурация окружения и они меняются, а состав потоков задан контрактом с 1С:УСК.
 */
public enum OneCStream {

    /** Полисы застрахованных вместе с программами и условиями обслуживания. Содержит персональные данные. */
    POLICIES,

    /**
     * Договоры страхования. Сохраняются только договоры добровольного медицинского страхования (ДМС). Страхователем
     * бывает человек, и тогда в теле сообщения его ФИО, то есть персональные данные.
     */
    INSURANCE_CONTRACTS,

    /** Контрагенты-юрлица: лечебные учреждения ({@code thisIsLPU = true}) и страхователи ({@code false}). */
    CONTRAGENTS,

    /** Справочник диагнозов по Международной классификации болезней (МКБ-10). */
    MKB10,

    /** Договоры с ЛПУ. */
    LPU_CONTRACTS,

    /** Страховые программы и перечень доступных по ним учреждений. */
    PROGRAMS,

    /** Виды обращений за медицинской помощью. */
    APPEAL_TYPES,

    /** Контактная информация: адрес и регион ЛПУ. */
    LPU_CONTACTS,

    /**
     * Прейскуранты. Единственный поток, который приходит двумя очередями: пакетами строк и финальным сообщением
     * со счётчиками. Какая из них, видно по имени очереди в строке сырья.
     */
    PRICE_LISTS,

    /** Услуги контрагентов по договорам. */
    CONTRAGENT_SERVICES
}
