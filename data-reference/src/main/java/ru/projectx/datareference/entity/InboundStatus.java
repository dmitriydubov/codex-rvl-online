package ru.projectx.datareference.entity;

/**
 * Что произошло с сырым сообщением после приёма. {@link #SKIPPED} и {@link #FAILED} различаются обязательно:
 * пропуск штатен и част, потому что поток несёт данные всех контрагентов 1С:УСК, а отказ означает поломку.
 * В одном статусе пришлось бы либо тревожиться из-за нормальной работы, либо не заметить настоящую ошибку.
 */
public enum InboundStatus {

    /** Принято, ещё не разобрано. С этого статуса начинается любая строка. */
    NEW,

    /**
     * Часть передачи прайса ждёт остальные сообщения: прайс услуги замещается целиком, и половина замещения хуже,
     * чем ничего. Если сообщение потерялось у источника, передача не соберётся и строки останутся здесь навсегда,
     * поэтому за давностью таких строк нужно следить.
     */
    BUFFERED,

    /** Разложено по таблицам справочников. Терминальный статус. */
    PROCESSED,

    /**
     * Справочник сообщением не пополнился: запись не наша или ссылается на запись, признанную не нашей. Это не значит,
     * что в базу ничего не записано: страхователь из потока контрагентов сохраняется в {@code insurers}. Что именно
     * произошло, говорит обязательная причина в {@code last_error}.
     */
    SKIPPED,

    /**
     * Сообщение ждёт запись справочника, которой ещё нет, и остальной поток не держит: 1С выгружает справочники
     * многими очередями и порядок не гарантирует. Разбор возьмёт его снова, когда родитель придёт или будет признан
     * не нашим, а если он не пришёл за срок ожидания, сообщение уходит в {@link #FAILED}.
     */
    AWAITING_PARENT,

    /**
     * Временная ошибка: недоступная база, таймаут, блокировка. Повтор назначен
     * на {@code next_retry_at} по лестнице задержек. Не терминальный.
     */
    RETRY,

    /**
     * Постоянная ошибка либо исчерпанная лестница повторов. Терминальный статус,
     * разбирает дежурный: сообщение лежит в базе целиком, его можно посмотреть,
     * починить маппер и перевести строку обратно в {@link #NEW}.
     */
    FAILED
}
