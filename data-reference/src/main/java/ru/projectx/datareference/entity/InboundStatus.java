package ru.projectx.datareference.entity;

/**
 * Что произошло с сырым сообщением после приёма.
 *
 * <p>Различать {@link #SKIPPED} и {@link #FAILED} обязательно. Пропуск — штатный
 * и частый исход: один поток 1С несёт данные всех контрагентов 1С:УСК, а нам нужны
 * только РВЛ-ЛПУ и их договоры. Отказ — это поломка. Свалить их в один статус значит
 * либо алертить на нормальную работу, либо не заметить настоящую ошибку.
 */
public enum InboundStatus {

    /** Принято, ещё не разобрано. С этого статуса начинается любая строка. */
    NEW,

    /**
     * Часть многочастной передачи, ожидающая остальных её сообщений. Применить такое
     * сообщение поодиночке нельзя — прайс по услуге замещается целиком, и половина
     * замещения хуже, чем ничего.
     *
     * <p><b>Не терминальный.</b> Переходит в {@link #PROCESSED} или {@link #FAILED},
     * когда передача соберётся. Передача, которая не соберётся никогда (сообщение
     * потерялось у источника), остаётся здесь навсегда — поэтому за давностью
     * буферизованных строк нужно следить.
     *
     * <p>Сегодня сюда попадают только прайсы (ТЗ-9) — единственный поток, приходящий
     * частями.
     */
    BUFFERED,

    /** Разложено по таблицам справочников. Терминальный статус. */
    PROCESSED,

    /**
     * Справочник, за которым шли в этот поток, сообщением не пополнился: контрагент
     * не РВЛ, программа не РВЛ, услуга чужого договора. Не ошибка — причина обязательна.
     *
     * <p><b>Не читается как «в базу ничего не записано».</b> У ТЗ-3 сюда попадает и
     * страхователь: строка в {@code insurers} создаётся, но санаторием сообщение
     * не стало — см. {@code ContragentMapper#applyInsurer}. Что именно произошло,
     * говорит причина в {@code last_error}, и читать нужно её, а не сам статус.
     *
     * <p>Сюда же попадает сообщение, родитель которого ещё не приехал (риск, названный
     * в самом контракте). Такие строки переобрабатываются вручную — переводом обратно
     * в {@link #NEW} обычным SQL. Повторное применение безопасно: все потоки пишут
     * upsert-ом по {@code external_id}.
     */
    SKIPPED,

    /**
     * Временная ошибка: недоступная база, таймаут, блокировка. Повтор назначен
     * на {@code next_retry_at} по лестнице задержек. Не терминальный.
     */
    RETRY,

    /**
     * Постоянная ошибка либо исчерпанная лестница повторов. Терминальный статус,
     * разбирает дежурный: сообщение лежит в базе целиком, его можно посмотреть,
     * починить маппер и перевести строку обратно в {@link #NEW}.
     */
    FAILED
}
